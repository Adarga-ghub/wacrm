// ------------------------------------------------------------
// Automation-side Meta sender.
//
// Mirrors the logic in src/app/api/whatsapp/send/route.ts but uses
// the service-role client (engine has no cookies) and accepts the
// user / conversation / contact identifiers the engine already has
// on hand. Kept here (rather than refactoring the user-facing send
// route) to avoid risk to the working manual-send path — they can
// converge in a later refactor.
// ------------------------------------------------------------

interface SendTextArgs {
  /** Account-level tenancy key. Drives contact + whatsapp_config
   *  lookups so an automation authored by user A still sends through
   *  the WhatsApp number user B saved on the same account. */
  accountId: string
  /** Original author of the automation/flow — used for INSERT audit
   *  columns (messages.sender_id-ish) and for resolving the agent's
   *  identity in logs. Not consulted for tenancy. */
  userId: string
  conversationId: string
  contactId: string
  text: string
}

interface SendTemplateArgs {
  accountId: string
  userId: string
  conversationId: string
  contactId: string
  templateName: string
  language?: string
  params?: string[]
}

export async function engineSendText(
  args: SendTextArgs,
): Promise<{ whatsapp_message_id: string; content_text: string }> {
  return sendViaMeta({ ...args, kind: 'text' })
}

export async function engineSendTemplate(
  args: SendTemplateArgs,
): Promise<{ whatsapp_message_id: string; content_text: string }> {
  return sendViaMeta({ ...args, kind: 'template' })
}

interface SendAudioArgs {
  accountId: string
  userId: string
  conversationId: string
  contactId: string
  /** Public URL into the CRM's own storage (chat-media bucket) that
   *  Meta fetches at send time — never an externally supplied link. */
  mediaUrl: string
}

/**
 * Send a "Send Audio" automation step as a WhatsApp voice note.
 *
 * Mirrors `engineSendMedia` in `@/lib/flows/meta-send.ts` (same
 * contact/config lookup + phone-variant retry), but scoped to audio and,
 * unlike that function, persists `media_url` on the `messages` insert so
 * the bot-sent voice note is actually playable in the CRM's own inbox
 * thread (see `message-media.tsx`, which reads `messages.media_url`) —
 * not just delivered to the customer.
 */
export async function engineSendAudio(
  args: SendAudioArgs,
): Promise<{ whatsapp_message_id: string }> {
  const db = supabaseAdmin()

  const { data: contact, error: contactErr } = await db
    .from('contacts')
    .select('id, phone')
    .eq('id', args.contactId)
    .eq('account_id', args.accountId)
    .maybeSingle()
  if (contactErr || !contact?.phone) {
    throw new Error('contact not found for this account')
  }

  const sanitized = sanitizePhoneForMeta(contact.phone)
  if (!isValidE164(sanitized)) {
    throw new Error(`contact phone invalid: ${contact.phone}`)
  }

  const { data: config, error: configErr } = await db
    .from('whatsapp_config')
    .select('*')
    .eq('account_id', args.accountId)
    .single()
  if (configErr || !config) {
    throw new Error('WhatsApp not configured for this account')
  }

  const accessToken = decrypt(config.access_token)

  const attempt = async (phone: string): Promise<string> => {
    const r = await sendMediaMessage({
      phoneNumberId: config.phone_number_id,
      accessToken,
      to: phone,
      kind: 'audio',
      link: args.mediaUrl,
    })
    return r.messageId
  }

  const variants = phoneVariants(sanitized)
  let workingPhone = sanitized
  let waMessageId = ''
  let lastError: unknown = null
  for (const v of variants) {
    try {
      waMessageId = await attempt(v)
      workingPhone = v
      lastError = null
      break
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err)
      if (!isRecipientNotAllowedError(msg)) throw err
      lastError = err
    }
  }
  if (lastError) throw lastError

  if (workingPhone !== sanitized) {
    await db.from('contacts').update({ phone: workingPhone }).eq('id', contact.id)
  }

  const { error: msgErr } = await db.from('messages').insert({
    conversation_id: args.conversationId,
    sender_type: 'bot',
    content_type: 'audio',
    content_text: null,
    media_url: args.mediaUrl,
    message_id: waMessageId,
    status: 'sent',
  })
  if (msgErr) {
    throw new Error(`sent to Meta but DB insert failed: ${msgErr.message}`)
  }

  await db
    .from('conversations')
    .update({
      last_message_text: '[audio]',
      last_message_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    })
    .eq('id', args.conversationId)

  return { whatsapp_message_id: waMessageId }
}

/**
 * Best-effort filename for a "Send PDFs" document: the user's title,
 * sanitized of path-hostile characters, with the uploaded file's real
 * extension appended if the title doesn't already end with it. This is
 * what WhatsApp displays next to the document icon in the customer's
 * chat — the whole reason the builder collects a title per file instead
 * of sending the raw uploaded filename (e.g. `1789-invoice.pdf`).
 */
function documentFilename(title: string, mediaUrl: string): string {
  let ext = '.pdf'
  try {
    const pathname = new URL(mediaUrl).pathname
    const match = /\.[^./]+$/.exec(pathname)
    if (match) ext = match[0].toLowerCase()
  } catch {
    // Malformed URL (shouldn't happen — it's our own storage's public
    // URL) — fall back to .pdf.
  }
  const safe = title.trim().replace(/[\\/:*?"<>|]+/g, ' ').replace(/\s+/g, ' ').trim() || 'document'
  return safe.toLowerCase().endsWith(ext) ? safe : `${safe}${ext}`
}

